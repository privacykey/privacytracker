// Third-party notices for the Rust backend (Phase 6, batch 5b).
//
// The Node build's disclosures come from package.json, which /legal reads
// directly. The Rust build ships compiled crates instead, so the list has
// to be taken from cargo: this walks the dependency graph of the desktop
// shell built with `--features rust-backend`, for one macOS target, and
// writes two things:
//
//   src-tauri/THIRD-PARTY-RUST.md   every crate that can end up in the
//                                   binary, with version, licence and
//                                   repository. Committed, and staged into
//                                   the bundle beside NOTICE, LICENSE and
//                                   core/V8-LICENSE.
//   lib/rust-crates.json            a summary /legal renders: the licence
//                                   breakdown and the crates we chose
//                                   ourselves. Small on purpose, because a
//                                   client component imports it.
//
// Only NORMAL dependencies are walked. Build dependencies (syn, quote,
// proc-macro2 and friends) run at compile time and their code does not
// ship; dev dependencies are tests. Both are excluded, and the file says
// so, because a notice that quietly includes them reads as if it were the
// shipped set.
//
// Run: `pnpm notices:rust`. CI regenerates and diffs, so a dependency
// change that is not disclosed fails the build rather than shipping.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");

/** One target is enough for a notice: the crate set is the same on both
 *  macOS architectures, and filtering keeps Windows-only crates out of a
 *  list that claims to describe what ships. */
const TARGET = "aarch64-apple-darwin";

/** Ours, not third party. */
const OURS = new Set(["privacytracker", "privacytracker-core"]);

function metadata() {
  const json = execFileSync(
    "cargo",
    [
      "metadata",
      "--manifest-path",
      path.join(repo, "src-tauri", "Cargo.toml"),
      "--no-default-features",
      "--features",
      "rust-backend",
      "--filter-platform",
      TARGET,
      "--format-version",
      "1",
      "--locked",
    ],
    { cwd: repo, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  );
  return JSON.parse(json);
}

/** Every crate reachable from the shell through normal dependencies. */
function shipped(meta) {
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const root = meta.resolve.root ?? meta.workspace_members[0];
  const seen = new Set();
  const queue = [root];
  while (queue.length > 0) {
    const id = queue.pop();
    if (seen.has(id)) {
      continue;
    }
    seen.add(id);
    for (const dep of nodes.get(id)?.deps ?? []) {
      const normal = dep.dep_kinds.some((kind) => kind.kind === null);
      if (normal && !seen.has(dep.pkg)) {
        queue.push(dep.pkg);
      }
    }
  }
  return [...seen]
    .map((id) => byId.get(id))
    .filter((pkg) => pkg && !OURS.has(pkg.name))
    .sort(
      (a, b) =>
        a.name.localeCompare(b.name) || a.version.localeCompare(b.version)
    );
}

/** The crates we picked ourselves: the shell's and the core's own
 *  dependency lists, which is what a reader wants named. */
function direct(meta) {
  const chosen = new Map();
  for (const pkg of meta.packages) {
    if (!OURS.has(pkg.name)) {
      continue;
    }
    for (const dep of pkg.dependencies) {
      if (dep.kind === "dev" || dep.kind === "build" || OURS.has(dep.name)) {
        continue;
      }
      chosen.set(dep.name, true);
    }
  }
  return chosen;
}

const meta = metadata();
const crates = shipped(meta);
const chosen = direct(meta);
const licenses = {};
for (const crate of crates) {
  const id = crate.license ?? "(not declared)";
  licenses[id] = (licenses[id] ?? 0) + 1;
}

const lines = [
  "# Third-party Rust crates",
  "",
  "The desktop app built on the Rust backend links the crates below. It is",
  `generated by \`pnpm notices:rust\` from \`cargo metadata\` for ${TARGET},`,
  "and CI fails if it is out of date.",
  "",
  "Only normal dependencies are listed: build dependencies run at compile",
  "time and their own code does not ship, and dev dependencies are tests.",
  "",
  `${crates.length} crates, by licence:`,
  "",
  ...Object.entries(licenses)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([id, count]) => `- ${id}: ${count}`),
  "",
  "| Crate | Version | Licence | Source |",
  "| --- | --- | --- | --- |",
  ...crates.map(
    (crate) =>
      `| ${crate.name} | ${crate.version} | ${crate.license ?? "(not declared)"} | ${crate.repository ?? ""} |`
  ),
  "",
  "The app also carries `NOTICE`, `LICENSE` and `V8-LICENSE`: the last covers",
  "the ports of V8's date parser and JSON error messages in the core.",
  "",
];
writeFileSync(
  path.join(repo, "src-tauri", "THIRD-PARTY-RUST.md"),
  `${lines.join("\n")}`
);

const summary = {
  // Regenerate with `pnpm notices:rust`; CI diffs it.
  target: TARGET,
  crates: crates.length,
  licenses: Object.fromEntries(
    Object.entries(licenses).sort(
      (a, b) => b[1] - a[1] || a[0].localeCompare(b[0])
    )
  ),
  direct: crates
    .filter((crate) => chosen.has(crate.name))
    .map((crate) => ({
      name: crate.name,
      version: crate.version,
      license: crate.license ?? "(not declared)",
      repository: crate.repository ?? null,
    })),
};
writeFileSync(
  path.join(repo, "lib", "rust-crates.json"),
  `${JSON.stringify(summary, null, 2)}\n`
);

console.log(
  `notices: ${crates.length} crates (${summary.direct.length} chosen directly) for ${TARGET}`
);
